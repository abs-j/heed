// Bundles src/lib/index.ts -> lib.js and src/content/main.js -> content.js (both loaded by the manifest).
import { build } from "esbuild";
await build({
  entryPoints: ["src/lib/index.ts"], outfile: "lib.js", bundle: true, format: "iife",
  target: "chrome120", legalComments: "none",
  banner: { js: "// GENERATED by `npm run build` from src/lib. Do not edit by hand." }
});
await build({
  entryPoints: ["src/content/main.js"], outfile: "content.js", bundle: true, format: "iife",
  target: "chrome120", legalComments: "none",
  banner: { js: "// GENERATED by `npm run build` from src/content. Do not edit by hand." }
});
console.log("built lib.js, content.js");
